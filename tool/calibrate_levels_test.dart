// Tunes every level's move limit against a bot and writes
// lib/game/level_tuning.dart.
//
// Run from the project root after changing level generation:
//   flutter test tool/calibrate_levels_test.dart
//
// For each level the bot plays [_seeds] games with no move limit and the
// number of moves each win took is recorded. Targets are scaled so a level
// takes a sensible number of moves (longer as the game goes on), and the
// move limit is then set so the bot would win a chosen share of the games:
// about 95% on the easiest levels down to about 35% on the hardest. If the
// bot cannot reach that share even with unlimited moves, the targets are
// scaled down or another layout variant is tried.

import 'dart:io';
import 'dart:math' as math;

import 'package:block_puzzle/game/levels.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:block_puzzle/game/level_bot.dart';

const int _seeds = 24;
const List<int> _scalesUp = [100, 125, 150, 180, 220, 270, 330];
const List<int> _scalesDown = [85, 70, 55, 40];
const int _variants = 6;

/// Share of bot games that should be winnable at difficulty [d].
double desiredWinRate(double d) => 0.95 - 0.6 * d;

/// Fewest moves the bot's typical win should take at difficulty [d].
double minLength(double d) => 8 + 14 * d;

/// Most moves a level should allow, so none drags on.
double maxLength(double d) => 30 + 15 * d;

/// Bot results for one version of a level.
class _Trial {
  _Trial(this.spec, this.variant, this.scale, this.wins);

  final LevelSpec spec;
  final int variant;
  final int scale;
  final List<int> wins; // sorted move counts of the games won

  int get median => wins.isEmpty ? 0 : wins[wins.length ~/ 2];
}

_Trial _run(int n, int variant, int scale) {
  final spec =
      LevelSpec.generate(n, variant: variant, targetScale: scale / 100);
  final wins = [for (var s = 0; s < _seeds; s++) botMovesToWin(spec, s)]
      .whereType<int>()
      .toList()
    ..sort();
  return _Trial(spec, variant, scale, wins);
}

void main() {
  test('calibrate levels', () {
    final rows = <List<int>>[];
    final report = StringBuffer();
    for (var n = 1; n <= LevelSpec.count; n++) {
      final d = LevelSpec.difficultyOf(n);
      final need = (desiredWinRate(d) * _seeds).ceil();
      final minLen = minLength(d);

      // Find a layout the bot can beat often enough, then grow its targets
      // until it takes long enough (or stops being beatable often enough).
      _Trial? chosen;
      for (var v = 0; v < _variants && chosen == null; v++) {
        for (final scale in [100, ..._scalesDown]) {
          final t = _run(n, v, scale);
          if (t.wins.length >= need) {
            chosen = t;
            break;
          }
        }
      }
      if (chosen != null && chosen.scale == 100) {
        for (final scale in _scalesUp.skip(1)) {
          if (chosen!.median >= minLen) break;
          final t = _run(n, chosen.variant, scale);
          if (t.wins.length < need) break;
          // Gem and ice counts are capped by the blocks on the board, so a
          // bigger scale may change nothing.
          if (t.median <= chosen.median) break;
          chosen = t;
        }
      }

      // Too long: shrink the targets until it fits.
      if (chosen != null && chosen.wins[need - 1] > maxLength(d)) {
        for (final scale in _scalesDown.where((s) => s < chosen!.scale)) {
          final t = _run(n, chosen!.variant, scale);
          if (t.wins.length < need) break;
          chosen = t;
          if (t.wins[need - 1] <= maxLength(d)) break;
        }
      }

      List<int> row;
      String summary;
      if (chosen != null) {
        final moves = math.max(5, chosen.wins[need - 1]);
        row = [chosen.variant, chosen.scale, moves];
        final spec = chosen.spec;
        final goals =
            spec.goals.map((g) => '${g.type.name} ${g.target}').join(' + ');
        summary =
            'level $n  d=${d.toStringAsFixed(2)}  v${chosen.variant} ${chosen.scale}%  '
            '$moves moves  bot ${chosen.wins.where((w) => w <= moves).length}/$_seeds  ($goals'
            '${spec.ice.isNotEmpty ? ', ${spec.ice.length} ice' : ''})';
      } else {
        // Nothing reached the target share: use the easiest version with
        // a generous limit.
        final spec = LevelSpec.generate(n, targetScale: _scalesDown.last / 100);
        row = [0, _scalesDown.last, spec.moves * 2];
        summary = 'level $n  FALLBACK ${spec.moves * 2} moves';
      }
      rows.add(row);
      report.writeln(summary);
    }

    final out = StringBuffer()
      ..writeln(
          '// Generated by tool/calibrate_levels_test.dart. Do not edit by hand.')
      ..writeln('//')
      ..writeln(
          '// One row per level: [layout variant, target scale %, move limit].')
      ..writeln()
      ..writeln('const List<List<int>> kLevelTuning = [');
    for (var i = 0; i < rows.length; i++) {
      out.writeln('  [${rows[i].join(', ')}], // ${i + 1}');
    }
    out.writeln('];');
    File('lib/game/level_tuning.dart').writeAsStringSync(out.toString());
    // ignore: avoid_print
    print(report);
  }, timeout: const Timeout(Duration(minutes: 30)));
}
